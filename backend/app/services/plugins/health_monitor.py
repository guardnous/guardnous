"""
Plugin Health Monitor — autonomous agent that watches for CVEs in our own scanner toolchain.

"GuardNous doesn't just scan your code for vulns — it monitors its own scanners."

This Celery task runs periodically to:
1. Check NVD/GitHub Security Advisories for CVEs affecting our scanners
2. Verify binary integrity (SHA-256 hash check)
3. Auto-rollback vulnerable versions
4. Notify admins of available updates
5. Generate supply-chain health reports
"""

from __future__ import annotations

import json
import logging
import time
from dataclasses import dataclass, field, asdict
from typing import Any

logger = logging.getLogger(__name__)


@dataclass
class SupplyChainAlert:
    """Alert generated by the health monitor."""
    alert_id: str
    severity: str              # critical, high, medium, low, info
    plugin_name: str
    alert_type: str            # cve_detected, integrity_failure, update_available, version_eol
    title: str
    description: str
    cve_ids: list[str] = field(default_factory=list)
    affected_version: str | None = None
    fixed_version: str | None = None
    auto_remediated: bool = False
    remediation_action: str | None = None
    timestamp: float = field(default_factory=time.time)

    def to_dict(self) -> dict:
        return asdict(self)


# Known CVE sources for each scanner
SCANNER_CPE_MAP = {
    "semgrep": {
        "vendor": "returntocorp",
        "product": "semgrep",
        "github_repo": "semgrep/semgrep",
    },
    "trivy": {
        "vendor": "aquasecurity",
        "product": "trivy",
        "github_repo": "aquasecurity/trivy",
    },
    "checkov": {
        "vendor": "bridgecrew",
        "product": "checkov",
        "github_repo": "bridgecrewio/checkov",
    },
    "gitleaks": {
        "vendor": "gitleaks",
        "product": "gitleaks",
        "github_repo": "gitleaks/gitleaks",
    },
    "tfsec": {
        "vendor": "aquasecurity",
        "product": "tfsec",
        "github_repo": "aquasecurity/tfsec",
    },
}


class PluginHealthMonitor:
    """
    Monitors the health and security of scanner plugins.

    Run as a Celery periodic task or on-demand from the admin UI.
    """

    def __init__(self, version_manager=None, redis_client=None):
        from app.services.plugins.version_manager import get_version_manager
        self._vm = version_manager or get_version_manager()
        self._redis = redis_client
        self._alerts: list[SupplyChainAlert] = []

    def run_full_check(self) -> dict[str, Any]:
        """
        Execute all health checks and return a supply-chain health report.

        Called by the Celery beat task `plugin_supply_chain_monitor`.
        """
        start = time.time()
        self._alerts = []

        # 1. Check for CVEs against our scanners
        cve_alerts = self._check_github_advisories()
        self._alerts.extend(cve_alerts)

        # 2. Verify binary integrity
        integrity_alerts = self._check_integrity()
        self._alerts.extend(integrity_alerts)

        # 3. Check for available updates
        update_alerts = self._check_updates()
        self._alerts.extend(update_alerts)

        # 4. Check for EOL / deprecated versions
        eol_alerts = self._check_eol_versions()
        self._alerts.extend(eol_alerts)

        # Build report
        report = {
            "timestamp": time.time(),
            "duration_ms": (time.time() - start) * 1000,
            "total_alerts": len(self._alerts),
            "critical_alerts": len([a for a in self._alerts if a.severity == "critical"]),
            "high_alerts": len([a for a in self._alerts if a.severity == "high"]),
            "alerts": [a.to_dict() for a in self._alerts],
            "plugins_checked": list(SCANNER_CPE_MAP.keys()),
            "auto_remediations": len([a for a in self._alerts if a.auto_remediated]),
        }

        # Persist to Redis for dashboard
        if self._redis:
            try:
                self._redis.setex(
                    "plugin_health_report",
                    86400,
                    json.dumps(report, default=str),
                )
            except Exception as exc:
                logger.warning("Failed to persist health report: %s", exc)

        logger.info(
            "Plugin health check complete: %d alerts (%d critical, %d high) in %.0fms",
            report["total_alerts"],
            report["critical_alerts"],
            report["high_alerts"],
            report["duration_ms"],
        )

        return report

    def _check_github_advisories(self) -> list[SupplyChainAlert]:
        """Check GitHub Security Advisories for our scanner repos."""
        alerts = []
        for plugin_name, info in SCANNER_CPE_MAP.items():
            try:
                advisories = self._fetch_github_advisories(info["github_repo"])
                active = self._vm.get_active_version(plugin_name)
                if not active:
                    continue

                for advisory in advisories:
                    affected_range = advisory.get("vulnerable_version_range", "")
                    if self._version_in_range(active.version, affected_range):
                        cve_id = advisory.get("cve_id", advisory.get("ghsa_id", "UNKNOWN"))
                        alert = SupplyChainAlert(
                            alert_id=f"{plugin_name}-{cve_id}",
                            severity=self._map_ghsa_severity(advisory.get("severity", "medium")),
                            plugin_name=plugin_name,
                            alert_type="cve_detected",
                            title=f"CVE detected in {plugin_name} {active.version}",
                            description=advisory.get("summary", "Security vulnerability detected"),
                            cve_ids=[cve_id],
                            affected_version=active.version,
                            fixed_version=advisory.get("patched_versions", None),
                        )

                        # Auto-remediate if policy allows
                        policy = self._vm.get_policy(plugin_name)
                        if policy.auto_rollback:
                            new_version = self._vm.flag_vulnerable(
                                plugin_name, active.version, [cve_id]
                            )
                            if new_version:
                                alert.auto_remediated = True
                                alert.remediation_action = (
                                    f"Auto-rolled back to {new_version.version}"
                                )

                        alerts.append(alert)

            except Exception as exc:
                logger.warning("Advisory check failed for %s: %s", plugin_name, exc)

        return alerts

    def _check_integrity(self) -> list[SupplyChainAlert]:
        """Verify SHA-256 hashes of all installed scanner binaries."""
        from app.services.plugins.integrity import MISMATCH, PluginIntegrityError, get_integrity

        alerts = []
        # The executables scans actually run (resolved on PATH), against their pins
        for plugin_name in SCANNER_CPE_MAP:
            try:
                status = get_integrity().check(plugin_name)
            except PluginIntegrityError as exc:
                alerts.append(SupplyChainAlert(
                    alert_id="integrity-pin-file", severity="critical", plugin_name=plugin_name,
                    alert_type="integrity_failure", title="Integrity pin file is unreadable",
                    description=str(exc),
                ))
                break
            if status.status == MISMATCH:
                alerts.append(SupplyChainAlert(
                    alert_id=f"{plugin_name}-integrity-active",
                    severity="critical",
                    plugin_name=plugin_name,
                    alert_type="integrity_failure",
                    title=f"{plugin_name} binary changed since it was approved — scans with it are blocked",
                    description=(
                        f"{status.path} has SHA-256 {status.sha256}; the approved hash is "
                        f"{status.expected_sha256}. If the scanner was upgraded deliberately, "
                        "approve the new binary. Otherwise investigate the host."
                    ),
                ))

        # Versions held in the download cache
        for plugin_name in SCANNER_CPE_MAP:
            results = self._vm.verify_integrity(plugin_name)
            for version, valid in results.items():
                if not valid:
                    alerts.append(SupplyChainAlert(
                        alert_id=f"{plugin_name}-integrity-{version}",
                        severity="critical",
                        plugin_name=plugin_name,
                        alert_type="integrity_failure",
                        title=f"Binary integrity check FAILED for {plugin_name} {version}",
                        description=(
                            f"SHA-256 hash mismatch detected for {plugin_name} {version}. "
                            f"The binary may have been tampered with. "
                            f"Immediate investigation required."
                        ),
                        affected_version=version,
                    ))
        return alerts

    def _check_updates(self) -> list[SupplyChainAlert]:
        """Check for available version updates."""
        alerts = []
        updates = self._vm.get_available_updates()
        for update in updates:
            alerts.append(SupplyChainAlert(
                alert_id=f"{update['plugin']}-update-{update['latest']}",
                severity="info",
                plugin_name=update["plugin"],
                alert_type="update_available",
                title=f"Update available: {update['plugin']} {update['current']} → {update['latest']}",
                description=(
                    f"A newer version of {update['plugin']} is available. "
                    f"Current: {update['current']}, Latest: {update['latest']}. "
                    f"Review changelog at {update['homepage']} before updating."
                ),
                affected_version=update["current"],
                fixed_version=update["latest"],
            ))
        return alerts

    def _check_eol_versions(self) -> list[SupplyChainAlert]:
        """Flag known EOL/deprecated scanner versions."""
        alerts = []
        # tfsec is deprecated in favor of Trivy
        active_tfsec = self._vm.get_active_version("tfsec")
        if active_tfsec:
            alerts.append(SupplyChainAlert(
                alert_id="tfsec-eol",
                severity="medium",
                plugin_name="tfsec",
                alert_type="version_eol",
                title="tfsec is deprecated — migrate to Trivy",
                description=(
                    "tfsec has been officially deprecated by Aqua Security. "
                    "All tfsec rules are now included in Trivy. "
                    "Consider migrating to Trivy for continued support."
                ),
                affected_version=active_tfsec.version,
            ))
        return alerts

    # ── GitHub Advisory API ──────────────────────────────────────────────

    @staticmethod
    def _fetch_github_advisories(repo: str) -> list[dict]:
        """Fetch security advisories from GitHub API."""
        try:
            import urllib.request
            url = f"https://api.github.com/repos/{repo}/security-advisories"
            req = urllib.request.Request(url, headers={
                "Accept": "application/vnd.github+json",
                "X-GitHub-Api-Version": "2022-11-28",
            })
            with urllib.request.urlopen(req, timeout=15) as resp:
                return json.loads(resp.read())
        except Exception:
            # Advisories API may require authentication or not exist
            return []

    @staticmethod
    def _version_in_range(version: str, range_str: str) -> bool:
        """Check if a version falls within a vulnerable range (simplified)."""
        if not range_str:
            return False
        try:
            from packaging.version import Version
            v = Version(version)
            # Simple range parsing: "< 1.2.3", ">= 1.0.0, < 1.2.3"
            for part in range_str.split(","):
                part = part.strip()
                if part.startswith("< "):
                    if v >= Version(part[2:]):
                        return False
                elif part.startswith("<= "):
                    if v > Version(part[3:]):
                        return False
                elif part.startswith(">= "):
                    if v < Version(part[3:]):
                        return False
                elif part.startswith("> "):
                    if v <= Version(part[2:]):
                        return False
            return True
        except Exception:
            return False

    @staticmethod
    def _map_ghsa_severity(severity: str) -> str:
        """Map GitHub Advisory severity to our severity levels."""
        mapping = {
            "critical": "critical",
            "high": "high",
            "moderate": "medium",
            "medium": "medium",
            "low": "low",
        }
        return mapping.get(severity.lower(), "medium")

    # ── Summary for agents ───────────────────────────────────────────────

    def get_supply_chain_summary(self) -> str:
        """
        Generate a human-readable supply chain health summary.

        Used by the AI agents when asked about plugin/scanner health.
        """
        report = self.run_full_check()
        lines = ["## Scanner Supply Chain Health Report", ""]

        if report["critical_alerts"] > 0:
            lines.append(f"🔴 **{report['critical_alerts']} CRITICAL alerts** — immediate action required")
        if report["high_alerts"] > 0:
            lines.append(f"🟠 **{report['high_alerts']} HIGH alerts** — action recommended")

        if report["total_alerts"] == 0:
            lines.append("✅ All scanner plugins are healthy — no vulnerabilities detected.")
        else:
            lines.append("")
            for alert in report["alerts"]:
                icon = {"critical": "🔴", "high": "🟠", "medium": "🟡", "low": "⚪", "info": "ℹ️"}.get(
                    alert["severity"], "❓"
                )
                lines.append(f"- {icon} **{alert['title']}**")
                if alert.get("auto_remediated"):
                    lines.append(f"  ✅ Auto-remediated: {alert['remediation_action']}")

        lines.append("")
        lines.append(f"Plugins checked: {', '.join(report['plugins_checked'])}")
        if report["auto_remediations"] > 0:
            lines.append(f"Auto-remediations applied: {report['auto_remediations']}")

        return "\n".join(lines)


# ── Celery task registration ─────────────────────────────────────────────────

# The beat schedule for these tasks lives in app/tasks/celery_app.py.

from app.tasks.celery_app import celery_app  # noqa: E402


@celery_app.task(name="agent.plugin_supply_chain_monitor")
def check_plugin_supply_chain():
    """Celery task: full supply chain health check."""
    monitor = PluginHealthMonitor()
    return monitor.run_full_check()


@celery_app.task(name="agent.plugin_integrity_check")
def check_plugin_integrity():
    """Celery task: binary integrity verification only (fast)."""
    from app.services.plugins.version_manager import get_version_manager
    vm = get_version_manager()
    results = {}
    for plugin_name in SCANNER_CPE_MAP:
        results[plugin_name] = vm.verify_integrity(plugin_name)
    return results
